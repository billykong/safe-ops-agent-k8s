"""Render results/benchmarks.md from the raw samples written by
scripts/bench.sh.

Usage: report.py RESULTS_JSONL REPORT_MD
"""
import json, sys, statistics, datetime
results_f, report_f = sys.argv[1:3]
rows = [json.loads(l) for l in open(results_f)]
env = next(r for r in rows if r["kind"] == "env")
runsc, cpu, ncpu, kernel = env["runsc"], env["cpu"], env["ncpu"], env["kernel"]
workloads = next(r["items"] for r in rows if r["kind"] == "workloads")
errors = [r for r in rows if r["kind"] == "error"]
kv = {r["runtime"]: r["proc_version"] for r in rows if r["kind"] == "runtime"}
cpu_limit = next((r.get("cpu") for r in rows if r["kind"] == "runtime"), None) or "500m"

def stats(xs):
    xs = sorted(xs)
    return statistics.median(xs), xs[0], xs[-1]

out = []
lat = [r for r in rows if r["kind"] == "latency"]
groups = [("Warm-pool claim (gVisor)", "warm-claim", "gvisor"),
          ("Cold `Sandbox`, gVisor", "cold-sandbox", "gvisor"),
          ("Cold `Sandbox`, runc", "cold-sandbox", "runc")]
out.append("| Path | n | Ready: median (min-max) | First successful run: median (min-max) |\n| --- | --- | --- | --- |")
med = {}
for label, mode, rt in groups:
    g = [r for r in lat if r["mode"] == mode and r["runtime"] == rt]
    if not g:
        continue
    rm, rlo, rhi = stats([r["ready_ms"] for r in g])
    fm, flo, fhi = stats([r["first_run_ms"] for r in g])
    med[(mode, rt)] = (rm, fm)
    out.append(f"| {label} | {len(g)} | {rm:,.0f} ms ({rlo:,.0f}-{rhi:,.0f}) | {fm:,.0f} ms ({flo:,.0f}-{fhi:,.0f}) |")
latency_table = "\n".join(out)

bu = sorted((r for r in rows if r["kind"] == "burst"), key=lambda r: r["i"])
burst_table = ""
if bu:
    burst_table = (f"\n### Burst: {bu[0]['n']} claims at once, warm pool of {bu[0]['pool']}\n\n"
                   "| Claim (by finish order) | Ready | First successful run |\n| --- | --- | --- |\n"
                   + "\n".join(f"| {r['i']+1} | {r['ready_ms']:,.0f} ms | {r['first_run_ms']:,.0f} ms |" for r in bu) + "\n")

ov = [r for r in rows if r["kind"] == "overhead"]
descs = {"empty-run": "Empty run: executor starts a fresh Python for `pass` (its `duration_ms`)"}
descs.update({w["id"]: w["desc"] for w in workloads})
out = ["| Workload | runc: median (min-max) | gVisor: median (min-max) | gVisor / runc (medians) |\n| --- | --- | --- | --- |"]
def cell(xs):
    m, lo, hi = stats(xs)
    return f"{m*1000:,.1f} ms ({lo*1000:,.0f}-{hi*1000:,.0f})"
ratios = {}
for wid, desc in descs.items():
    by = {rt: [r["seconds"] for r in ov if r["workload"] == wid and r["runtime"] == rt] for rt in ("runc", "gvisor")}
    if not by["runc"] or not by["gvisor"]:
        out.append(f"| {desc} | - | - | missing samples |")
        continue
    rc, gv = statistics.median(by["runc"]), statistics.median(by["gvisor"])
    ratios[wid] = gv / rc
    out.append(f"| {desc} | {cell(by['runc'])} | {cell(by['gvisor'])} | **{gv/rc:.2f}x** |")
rt_by = {rt: [r["round_trip_s"] for r in ov if r["workload"] == "empty-run" and r["runtime"] == rt] for rt in ("runc", "gvisor")}
if all(rt_by.values()):
    rc, gv = statistics.median(rt_by["runc"]), statistics.median(rt_by["gvisor"])
    out.append(f"| Agent round trip for an empty run (HTTP + interpreter start), seen from the agent pod | {cell(rt_by['runc'])} | {cell(rt_by['gvisor'])} | **{gv/rc:.2f}x** |")
overhead_table = "\n".join(out)
reps = max((r["rep"] for r in ov), default=-1) + 1

now = env.get("time") or datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
with open(report_f, "w") as f:
    f.write(f"""# Benchmarks

Generated by `make bench` on {now}. Raw samples: [benchmarks.jsonl](benchmarks.jsonl); re-render with `python3 projects/01-sandboxed-code-exec/bench/report.py`.

**Environment.** kind (single node) on WSL2, kernel `{kernel}`; host CPU {cpu}, {ncpu} logical CPUs. gVisor `{runsc}`, default platform (systrap) and network stack (netstack); no `runsc` flags set. Cilium eBPF-only datapath. Node swap off for pods. Sandbox template: 500m CPU / 256 MiB limit, executor RLIMITs as in the P1 README. The executor image is preloaded into the node, so no cold start includes an image pull.

Kernel seen inside the sandbox: gVisor `{kv.get('gvisor', '?')[:80]}`; runc `{kv.get('runc', '?')[:80]}`.

## Startup latency

Measured from an in-cluster pod in the agent namespace (bench identity, same network policy as the agent), polling the API every 20 ms. **Ready** is when the claim (warm) or `Sandbox` (cold) reports `Ready`. **First successful run** is when `POST /run` with `print(1)` first returns its output: the number an agent actually waits for. The warm pool is refilled to full before every sample, and each cold `Sandbox` is deleted and gone before the next, so samples don't overlap.

{latency_table}
{burst_table}
## Runtime overhead: gVisor vs runc

Two `Sandbox`es built from the same template, one with `runtimeClassName: gvisor` removed (runc). Same image, memory limit, hardening and executor. Both get a {cpu_limit} CPU limit instead of the template's 500m: with 500m, CFS throttling in 100 ms periods made short workloads swing by 2x between runs. Each workload is submitted through the executor and times itself inside the sandbox with `time.perf_counter()`. {reps} repetitions, alternating which runtime goes first; the table shows medians.

{overhead_table}

### Reading the overhead numbers

- **The pure-Python loop is slower under gVisor for a reason outside gVisor.** User code runs natively, with no syscalls in that loop. On this host the gap comes from the Spectre v4 mitigation: the kernel forces Speculative Store Bypass Disable (SSBD) on seccomp-filtered processes (`spec_store_bypass_disable=seccomp`, the default), and every gVisor process (Sentry and systrap stubs) shows `Speculation_Store_Bypass: thread force mitigated`. runc's container seccomp filter opts out (`thread vulnerable`). Forcing SSBD on the runc process with `prctl` slowed the same loop from 233 to 389 ms, about gVisor's figure. How much SSBD costs depends on the code and the CPU (here AMD Zen 3): an interpreter loop suffers, while hashing in C barely does.
- **A tight CPU limit roughly doubles gVisor's overhead.** In earlier runs at the template's 500m limit, the ratios were about twice these: `getppid` 5-9x, `stat` 9-10x, small files 8-9x, loopback TCP 2.2-2.4x. The Sentry's work is charged to the pod's CPU quota alongside the user code (under systrap a syscall is handed between the stub thread and a Sentry thread), so a small quota throttles gVisor sandboxes more than runc ones. Size sandbox CPU limits with this in mind.
- **Syscalls, file metadata, process creation and the network stack** are where gVisor's design costs: each syscall traps to the Sentry (systrap), file operations go through gVisor's own VFS before reaching host files, and the TCP stack is gVisor's own netstack. Workloads that import many modules or spawn tools pay this the most; the empty-run row (a fresh Python start) is the floor for every agent run.
""")
    if errors:
        f.write("\n**Errors during the run:**\n\n" + "\n".join(f"- `{e['workload']}` on {e['runtime']} (rep {e['rep']}): `{e['stderr'][-200:]}`" for e in errors) + "\n")
print(open(report_f).read())
sys.exit(1 if errors else 0)
